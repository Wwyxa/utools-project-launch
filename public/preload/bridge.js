function handlePluginOut(isKill) {
  if (isKill === true) {
    stopAllProcesses();
    flushRuntimeRecords();
  }
}

function registerProcessCleanupHooks() {
  window.utools?.onPluginOut?.(handlePluginOut);
  process.once?.("SIGINT", () => {
    stopAllProcesses();
    flushRuntimeRecords();
    process.exit(130);
  });
  process.once?.("SIGTERM", () => {
    stopAllProcesses();
    flushRuntimeRecords();
    process.exit(143);
  });
}

registerProcessCleanupHooks();

